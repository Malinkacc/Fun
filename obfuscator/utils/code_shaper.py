# ==================== ГЛАВНАЯ ФУНКЦИЯ ====================

def shape_code(
    mask_name: str = 'octopus',
    rng: Optional[random.Random] = None,
    real_code: Optional[str] = None,
) -> str:
    """
    Формирует красивый ASCII-header в форме силуэта.
    
    Args:
        mask_name: имя маски
        rng: генератор случайных чисел (для будущих фич)
        real_code: если задан → header + пустая строка + real_code
                   если None → только header
    
    ВАЖНО: real_code НЕ модифицируется. Header идёт как --[[ ]] коммент.
    
    Returns:
        Валидный Lua-код с ASCII-фигуркой сверху.
    """
    if rng is None:
        rng = random.Random()
    
    mask = MASKS.get(mask_name, OCTOPUS_MASK)
    label = MASK_LABELS.get(mask_name, mask_name.upper())
    
    # Ширина маски (макс. длина строки)
    max_width = max(len(row) for row in mask)
    
    # Верхняя граница
    border_top = '╔' + '═' * (max_width + 2) + '╗'
    border_bottom = '╚' + '═' * (max_width + 2) + '╝'
    
    # Заголовок
    title = f' NZL STUDIO OBFUSCATOR │ {label} SHAPE '
    # Центрируем title
    title_padding_total = max_width - len(title) + 2
    if title_padding_total < 0:
        title_padding_total = 0
    title_left = title_padding_total // 2
    title_right = title_padding_total - title_left
    title_line = '║' + '─' * title_left + title + '─' * title_right + '║'
    
    # Собираем ASCII-header
    header_lines: List[str] = []
    header_lines.append('--[[')
    header_lines.append(border_top)
    header_lines.append(title_line)
    header_lines.append('║ ' + ' ' * max_width + ' ║')
    
    # Сама фигурка
    for row in mask:
        # Заменяем '#' на плотный ASCII-блок (лучше видно)
        # Используем ▓█▒░ или просто ###
        line_content = row.replace('#', '█')  # плотный блок
        # Дополняем справа до max_width
        padded = line_content.ljust(max_width)
        header_lines.append('║ ' + padded + ' ║')
    
    header_lines.append('║ ' + ' ' * max_width + ' ║')
    
    # Подпись внизу
    footer = ' discord.gg/c3kBtN9vXb '
    footer_padding = max_width - len(footer) + 2
    if footer_padding < 0:
        footer_padding = 0
    fl = footer_padding // 2
    fr = footer_padding - fl
    footer_line = '║' + '─' * fl + footer + '─' * fr + '║'
    header_lines.append(footer_line)
    header_lines.append(border_bottom)
    header_lines.append(']]')
    
    header = '\n'.join(header_lines)
    
    if real_code:
        return header + '\n\n' + real_code
    else:
        # Декоративный режим: возвращаем только header + пустой блок
        return header + '\n\n-- (decorative shape)\n'


