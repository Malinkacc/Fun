  elseif op == 141 then  -- [141] SETTABLE — regs[A][regs[B]] = regs[C]   (копия опкода 4)
    regs[A][regs[B]]=regs[C]
  elseif op == 46 then  -- [46] MATH_M2 — regs[A] = math.M2(regs[B])   <НЕТ в стандартной библиотеке>
    regs[A]=math.M2(regs[B])
  elseif op == 117 then  -- [117] SIGN — regs[A] = sign(regs[B])
    local c5=regs[B]regs[A]=c5>0 and 1 or(c5<0 and-1 or 0)
  elseif op == 49 then  -- [49] PACK_REGS — regs[A] = {regs[B]..regs[C]}
    regs[A]={}for t4=B,C do regs[A][t4-B+1]=regs[t4]end
  elseif op == 87 then  -- [87] SUB_AND_JUMP — regs[A] = regs[A] - regs[A+2]; pc+D   (странная семантика)
    regs[A]=regs[A]-regs[A+2]pc=pc+D
  elseif op == 188 then  -- [188] CALL — вызов regs[A](regs[A+1]..regs[A+B-1])
    local U1={}for j3=1,B-1 do U1[j3]=regs[A+j3]end local B2=regs[A]local e2={B2(unpack(U1,1,B-1))}local a2=C-1 if a2==-1 then a2=#e2 end for j3=1,a2 do regs[A+j3-1]=e2[j3]end
  elseif op == 41 then  -- [41] JUMPBACK — pc = pc - D   (прыжок назад)
    pc=pc-D
  elseif op == 151 then  -- [151] LEK — regs[A] = (regs[B] <= K[D+1])
    regs[A]=(regs[B]<=consts[D+1])
  -- [86] NOOP — заглушка (no-op) (вырезано: реального эффекта нет)
  elseif op == 207 then  -- [207] FORLOOP — числовой for: шаг/сравнение/условный прыжок pc+D
    regs[A]=regs[A]+regs[A+2]local _g2=regs[A+2]local _f2r if _g2>0 then _f2r=(regs[A]<=regs[A+1]) else _f2r=(regs[A]>=regs[A+1]) end if _f2r then regs[A+3]=regs[A]pc=pc+D end
end end end


